function renderTrpi() {
  const language = localStorage.getItem('sophie-language') === 'zh' ? 'zh' : 'en';
  const copy = trpiCopy[language];
  document.querySelectorAll('[data-trpi]').forEach((node) => { node.textContent = copy[node.dataset.trpi]; });
  const list = document.getElementById('trpi-timeline');
  list.replaceChildren(...copy.steps.map((step) => {
    const item = document.createElement('li');
    const number = document.createElement('span'); number.className = 'trpi-step-number'; number.textContent = step.marker;
    const content = document.createElement('div'); content.className = 'trpi-step-content';
    const heading = document.createElement('h3'); heading.textContent = step.title;
    const body = document.createElement('p'); body.textContent = step.body;
    const note = document.createElement('small'); note.textContent = step.note;
    content.append(heading, body, note); item.append(number, content); return item;
  }));
}

const trpiIds = ['story', 'process', 'brief', 'next'];
let hotspotTimer;

function showTrpiPanel(id, { scroll = true, updateHistory = true, toggle = false } = {}) {
  const choice = document.querySelector(`.trpi-choice[data-target="${id}"]`);
  if (!choice) return;
  const closing = toggle && choice.getAttribute('aria-expanded') === 'true';
  document.querySelectorAll('.trpi-choice').forEach((button) => {
    const active = !closing && button === choice;
    button.setAttribute('aria-expanded', String(active));
    button.classList.toggle('is-active', active);
    button.querySelector('.trpi-choice-arrow').textContent = active ? '×' : '↗';
    document.getElementById(`${button.dataset.target}-panel`).hidden = !active;
  });
  if (updateHistory) history.pushState(null, '', closing ? '#trpi-choices' : `#${id}`);
  if (scroll) {
    const destination = closing ? document.getElementById('trpi-choices') : document.getElementById(`${id}-panel`);
    const reducedMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches || document.documentElement.dataset.motion === 'off';
    requestAnimationFrame(() => destination.scrollIntoView({ behavior: reducedMotion ? 'auto' : 'smooth', block: 'start' }));
  }
}

function syncTrpiHash() {
  const id = location.hash.slice(1);
  if (trpiIds.includes(id)) showTrpiPanel(id, { scroll: false, updateHistory: false });
  else document.querySelectorAll('.trpi-choice[aria-expanded="true"]').forEach((button) => showTrpiPanel(button.dataset.target, { scroll: false, updateHistory: false, toggle: true }));
}

document.addEventListener('click', (event) => {
  if (event.target.closest('[data-lang]')) renderTrpi();
  const returnButton = event.target.closest('[data-return]');
  if (returnButton) { showTrpiPanel(returnButton.dataset.return, { toggle: true }); return; }
  const choice = event.target.closest('.trpi-choice');
  if (choice) { showTrpiPanel(choice.dataset.target, { toggle: true }); return; }
  const hotspot = event.target.closest('.trpi-hotspot');
  if (!hotspot) return;
  event.preventDefault();
  clearTimeout(hotspotTimer);
  document.querySelectorAll('.trpi-hotspot.is-selected').forEach((node) => node.classList.remove('is-selected'));
  const stage = document.getElementById('trpi-hero-stage');
  const reducedMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches || document.documentElement.dataset.motion === 'off';
  hotspot.classList.add('is-selected');
  stage.classList.add('is-navigating');
  const navigate = () => {
    showTrpiPanel(hotspot.dataset.target);
    hotspotTimer = setTimeout(() => { stage.classList.remove('is-navigating'); hotspot.classList.remove('is-selected'); }, reducedMotion ? 0 : 650);
  };
  if (reducedMotion) navigate(); else hotspotTimer = setTimeout(navigate, 280);
});

renderTrpi();
syncTrpiHash();
window.addEventListener('load', () => {
  const id = location.hash.slice(1);
  if (trpiIds.includes(id)) {
    const root = document.documentElement;
    const scrollBehavior = root.style.scrollBehavior;
    root.style.scrollBehavior = 'auto';
    document.getElementById(`${id}-panel`).scrollIntoView({ behavior: 'auto', block: 'start' });
    root.style.scrollBehavior = scrollBehavior;
  }
});
window.addEventListener('popstate', syncTrpiHash);
window.addEventListener('hashchange', syncTrpiHash);
