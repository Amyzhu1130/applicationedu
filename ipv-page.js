const ipvIds = ['question', 'reading', 'pathway', 'reflection'];
let ipvHotspotTimer;

function renderIpv() {
  const language = localStorage.getItem('sophie-language') === 'zh' ? 'zh' : 'en';
  const copy = ipvCopy[language];
  document.querySelectorAll('[data-ipv]').forEach((node) => { node.textContent = copy[node.dataset.ipv]; });
}

function showIpvPanel(id, { scroll = true, updateHistory = true, toggle = false } = {}) {
  const choice = document.querySelector(`.ipv-choice[data-target="${id}"]`);
  if (!choice) return;
  const closing = toggle && choice.getAttribute('aria-expanded') === 'true';
  document.querySelectorAll('.ipv-choice').forEach((button) => {
    const active = !closing && button === choice;
    button.setAttribute('aria-expanded', String(active));
    button.classList.toggle('is-active', active);
    button.querySelector('.ipv-choice-arrow').textContent = active ? '×' : '↗';
    document.getElementById(`${button.dataset.target}-panel`).hidden = !active;
  });
  if (updateHistory) history.pushState(null, '', closing ? '#ipv-choices' : `#${id}`);
  if (scroll) {
    const destination = closing ? document.getElementById('ipv-choices') : document.getElementById(`${id}-panel`);
    const reducedMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches || document.documentElement.dataset.motion === 'off';
    requestAnimationFrame(() => destination.scrollIntoView({ behavior: reducedMotion ? 'auto' : 'smooth', block: 'start' }));
  }
}

function syncIpvHash() {
  const id = location.hash.slice(1);
  if (ipvIds.includes(id)) showIpvPanel(id, { scroll: false, updateHistory: false });
  else document.querySelectorAll('.ipv-choice[aria-expanded="true"]').forEach((button) => showIpvPanel(button.dataset.target, { scroll: false, updateHistory: false, toggle: true }));
}

document.addEventListener('click', (event) => {
  if (event.target.closest('[data-lang]')) renderIpv();
  const returnButton = event.target.closest('[data-return]');
  if (returnButton) { showIpvPanel(returnButton.dataset.return, { toggle: true }); return; }
  const choice = event.target.closest('.ipv-choice');
  if (choice) { showIpvPanel(choice.dataset.target, { toggle: true }); return; }
  const hotspot = event.target.closest('.ipv-hotspot');
  if (!hotspot) return;
  event.preventDefault();
  clearTimeout(ipvHotspotTimer);
  document.querySelectorAll('.ipv-hotspot.is-selected').forEach((node) => node.classList.remove('is-selected'));
  const stage = document.getElementById('ipv-hero-stage');
  const reducedMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches || document.documentElement.dataset.motion === 'off';
  hotspot.classList.add('is-selected');
  stage.classList.add('is-navigating');
  const navigate = () => {
    showIpvPanel(hotspot.dataset.target);
    ipvHotspotTimer = setTimeout(() => { stage.classList.remove('is-navigating'); hotspot.classList.remove('is-selected'); }, reducedMotion ? 0 : 650);
  };
  if (reducedMotion) navigate(); else ipvHotspotTimer = setTimeout(navigate, 280);
});

renderIpv();
syncIpvHash();
window.addEventListener('load', () => {
  const id = location.hash.slice(1);
  if (ipvIds.includes(id)) document.getElementById(`${id}-panel`).scrollIntoView({ behavior: 'auto', block: 'start' });
});
window.addEventListener('popstate', syncIpvHash);
window.addEventListener('hashchange', syncIpvHash);
